export type ServiceButton =
  | { kind: "quiz"; label: string }
  | {
      kind: "form";
      label: string;
      /** `params.source` of the lead — where the form was opened. */
      source: string;
      variant?: "primary" | "secondary";
      icon?: string;
    }
  | { kind: "link"; label: string; url: string; icon?: string };

/** A table cell: plain text, or text with a link (`href` of the cell). */
export type ServiceCell = string | { value: string; href: string };

export type ServiceBlock =
  | { type: "hero"; lead?: string; buttons: ServiceButton[] }
  | { type: "richText"; heading?: string; markdown: string; width?: "narrow" | "normal" }
  | {
      type: "table";
      heading?: string;
      columns: string[];
      /** 0-based indexes of numeric columns (tabular figures, right alignment). */
      numeric?: number[];
      rows: ServiceCell[][];
      footnote?: string;
    }
  | {
      type: "callout";
      tone: "info" | "warning";
      title?: string;
      /** Bulleted items, markdown each. */
      items?: string[];
      /** Markdown under the items. */
      body?: string;
    }
  | {
      type: "steps";
      heading?: string;
      items: Array<{
        title: string;
        text?: string;
        link?: { label: string; url: string };
      }>;
    }
  | { type: "holesCalculator" }
  | { type: "download"; items: Array<{ title: string }> }
  | { type: "cta"; buttons: ServiceButton[] }
  | { type: "form"; label: string; source: string; accept: string[] };

